/**
 * Prints the BookNest opening hours.
 * This is a documentation comment: tools turn it into HTML docs.
 */
public class CommentStyles {

    public static void main(String[] args) {
        // A single-line comment: explains the next line.
        int openingHour = 9;

        /*
         * A multi-line comment.
         * Useful for a longer explanation.
         */
        int closingHour = 21;

        System.out.println("Open " + openingHour + ":00 to "
                + closingHour + ":00");
    }
}
