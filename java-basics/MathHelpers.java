public class MathHelpers {

    public static void main(String[] args) {
        System.out.println("max(12, 30) = " + Math.max(12, 30));
        System.out.println("min(12, 30) = " + Math.min(12, 30));
        System.out.println("abs(-7)     = " + Math.abs(-7));
        System.out.println("pow(2, 10)  = " + Math.pow(2, 10));
        System.out.println("sqrt(144)   = " + Math.sqrt(144));
        System.out.println("ceil(4.1)   = " + Math.ceil(4.1));
        System.out.println("floor(4.9)  = " + Math.floor(4.9));
        System.out.println("round(2.5)  = " + Math.round(2.5));
        System.out.println("round(-2.5) = " + Math.round(-2.5));
    }
}
